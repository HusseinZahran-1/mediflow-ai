interface LanguageValue {
  language: Language
  toggleLanguage: () => void
  t: (key: string, variables?: Record<string, string | number>) => string
  enumLabel: (value?: string | null) => string
  locale: string
}

const LanguageContext = createContext<LanguageValue | null>(null)

function interpolate(value: string, variables?: Record<string, string | number>) {
  if (!variables) return value
  return Object.entries(variables).reduce((text, [key, replacement]) => text.replaceAll(`{${key}}`, String(replacement)), value)
}

export function LanguageProvider({ children }: PropsWithChildren) {
  const [language, setLanguage] = useState<Language>(() => {
    const stored = localStorage.getItem('mediflow_language')
    if (stored === 'ar' || stored === 'en') return stored
    return navigator.language.toLowerCase().startsWith('ar') ? 'ar' : 'en'
  })

  useEffect(() => {
    localStorage.setItem('mediflow_language', language)
    document.documentElement.lang = language
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr'
  }, [language])

  const value = useMemo<LanguageValue>(() => ({
    language,
    toggleLanguage: () => setLanguage((current) => current === 'en' ? 'ar' : 'en'),
    t: (key, variables) => interpolate((language === 'ar' ? ar[key] : en[key]) || en[key] || key, variables),
    enumLabel: (item) => {
      if (!item) return language === 'ar' ? 'غير محددة' : 'Not assigned'
      return language === 'ar' ? enumAr[item] || item.replaceAll('_', ' ') : item.replaceAll('_', ' ')
    },
    locale: language === 'ar' ? 'ar-JO' : 'en-GB',
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const value = useContext(LanguageContext)
  if (!value) throw new Error('useLanguage must be used inside LanguageProvider')
  return value
}
